async function saveCurrencyCodesToFile() {
  // 1. Dùng .map() để lấy ra mảng các currencyCode
  const currencyCodes = countrySeed.map(country => ({
  code: country.currencyCode,
  symbol: country.currencySymbol
}));

  // 2. Chuyển các object thành chuỗi JSON (hoặc định dạng text tùy ý), mỗi phần tử 1 dòng
  const fileContent = currencyCodes.map(item => JSON.stringify(item)).join('\n');

  // 3. Ghi ra file text (ví dụ: currencies.txt)
  try {
    await writeFile('currencycode.txt', fileContent, 'utf-8');
    console.log('Đã lưu thành công các currencyCode vào file currencies.txt!');
  } catch (error) {
    console.error('Lỗi khi ghi file:', error);
  }
}

